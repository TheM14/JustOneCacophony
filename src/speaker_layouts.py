def _make_layout(name: str, item: dict) -> SpeakerLayout:
    return SpeakerLayout(
        name=name,
        out_ch_config=item["out_ch_config"],
        speaker_bitfield=item["speaker_bitfield"],
        channels=item["channels"],
        internal_to_standard=item["internal_to_standard"],
        regions=tuple(RegionGeometry(**region) for region in item["regions"]),
    )


SPEAKER_LAYOUTS = {name: _make_layout(name, item) for name, item in _RAW_LAYOUTS.items()}

