"""Standard speaker-layout geometry used by the spatial renderer.

Coordinates are unsigned Q15 room coordinates. This is geometry/topology data,
not a sampled gain table.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class RegionGeometry:
    coordinates_q15: tuple[tuple[int, int, int], ...]
    speaker_ids: tuple[int, ...]
    axis0_groups: tuple[tuple[int, ...], ...]
    axis1_groups: tuple[tuple[int, ...], ...]
    mode: int


@dataclass(frozen=True)
class SpeakerLayout:
    name: str
    out_ch_config: int
    speaker_bitfield: int
    channels: tuple[str, ...]
    internal_to_standard: tuple[int, ...]
    regions: tuple[RegionGeometry, ...]

    @property
    def channel_count(self) -> int:
        return len(self.channels)


