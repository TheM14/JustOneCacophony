SPEAKER_LAYOUT_CHOICES = tuple(SPEAKER_LAYOUT_ALIASES)
SPEAKER_LAYOUT_DISPLAY_NAMES = {value: key for key, value in SPEAKER_LAYOUT_ALIASES.items()}


def get_speaker_layout(name: str) -> SpeakerLayout:
    key = SPEAKER_LAYOUT_ALIASES.get(name, name)
    try:
        return SPEAKER_LAYOUTS[key]
    except KeyError as exc:
        raise ValueError(f"unsupported speaker layout: {name}") from exc


def speaker_layout_display_name(layout: str | SpeakerLayout) -> str:
    target = get_speaker_layout(layout) if isinstance(layout, str) else layout
    return SPEAKER_LAYOUT_DISPLAY_NAMES[target.name]
